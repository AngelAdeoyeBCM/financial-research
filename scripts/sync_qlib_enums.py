"""Generate src/incolor/ontology/qlib_enums.py from QLib's C# Market enums.

QLib (BlueCrest.QR.QLib.Core) is the firm's market vocabulary. Its closed
classification enums become StrEnums with identical values, so ontology code
uses QLib's own strings. Its code lists (currencies, countries, reference
indices) are open in QLib, whose parsers accept any string at runtime, so they
become frozensets of the hard-coded core rather than enums.

Usage:
    python scripts/sync_qlib_enums.py                 # rewrite the module
    python scripts/sync_qlib_enums.py --check         # exit 1 if it is stale
    python scripts/sync_qlib_enums.py --source <dir>  # another QLib checkout
"""

import argparse
import re
import sys
from pathlib import Path

DEFAULT_SOURCE = Path(r'C:\src\FO\JunkoMarket\trunk\src\BlueCrest.QR.QLib.Core.Src\Market')
TARGET = Path(__file__).resolve().parents[1] / 'src' / 'incolor' / 'ontology' / 'qlib_enums.py'

# (C# class = Python class, file under Market/, docstring). Add rows to mirror more enums.
ENUMS = (
    ('YellowKey', 'Enums/YellowKey.cs', 'Bloomberg yellow key (market sector).'),
    ('BondClassification', 'Enums/BondClassification.cs', 'Yellow key plus Infl and Floater (bndcnv class).'),
    ('AssetType', 'Enums/AssetType.cs', 'Traded asset type: bond, bond future, IR swap, FX forward, ...'),
    ('CommodityType', 'Enums/CommodityType.cs', 'Commodity group.'),
    ('InstrumentCategory', 'Enums/InstrumentCategory.cs', 'How a rate index curve point is quoted.'),
    ('MarketType', 'Enums/MarketType.cs', 'Curve market: rates, fx or hybrid.'),
    ('IndexIdentifier', 'Enums/IndexIdentifier.cs', 'Equity index with a QLib definition (eqidx[...]).'),
    ('CdsIndexName', 'Enums/CdsIndexName.cs', 'Credit index family (cdsidx[...]).'),
    ('CallPut', 'Enums/CallPut.cs', 'Option payoff: call, put or straddle.'),
)
CODE_SETS = (
    ('CURRENCY_CODES', 'Instrument/CurrencyCode.cs', 'CurrencyCode'),
    ('COUNTRY_CODES', 'Enums/CountryCode.cs', 'CountryCode'),
    ('REFERENCE_INDICES', 'Instrument/ReferenceIndex.cs', 'ReferenceIndex'),
)

_ID_KEY = re.compile(r'IdKey\s*=\s*"([^"]+)"')
# `Field = new Cls("value", ...)` or a bare `new Cls("value")` inside an array initialiser.
_NEW = re.compile(r'(?:\b(\w+)\s*=\s*)?new\s+(\w+)\s*\(\s*@?"([^"]*)"')


def _parse(text: str, cls: str) -> list[tuple[str | None, str]]:
    """(field name or None, value) for each instance of `cls` or a subclass declared in `text`."""
    classes = {cls, *re.findall(r'class\s+(\w+)\s*:\s*' + cls + r'\b', text)}
    found: list[tuple[str | None, str]] = []
    seen: set[str] = set()
    for field, made, value in _NEW.findall(text):
        if made in classes and value not in seen:
            seen.add(value)
            found.append((field or None, value))
    return found


def _member(field: str | None, value: str) -> str:
    """Python member name: the C# field in upper snake case, else the value.

    InterestRateFuture -> INTEREST_RATE_FUTURE; 'iTraxx Europe Crossover' -> ITRAXX_EUROPE_CROSSOVER.
    """
    name = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', field) if field else value
    name = re.sub(r'\W+', '_', name).strip('_').upper()
    if name.replace('_', '') == 'UNKNOWN':
        name = 'UNKNOWN'
    return f'_{name}' if name[0].isdigit() else name


def render(source: Path) -> str:
    """Source text of the generated module."""
    lines = [
        '"""QLib market enums. Generated by scripts/sync_qlib_enums.py; do not edit.',
        '',
        f'Source: QLib {source.parent.name}/{source.name} (default checkout: JunkoMarket trunk).',
        '',
        'Closed QLib classification enums are StrEnums with QLib\'s own values. QLib',
        'accepts any currency, country or reference-index code at runtime, so those',
        'are frozensets of its hard-coded core, not closed lists.',
        '"""',
        '',
        'from enum import StrEnum',
        '',
    ]
    id_keys: list[tuple[str, str]] = []
    for cls, rel, doc in ENUMS:
        text = (source / rel).read_text(encoding='utf-8-sig')
        id_key = _ID_KEY.search(text)
        if id_key is None:
            raise ValueError(f'{rel}: no IdKey')
        id_keys.append((cls, id_key[1]))
        members = [(_member(field, value), value) for field, value in _parse(text, cls)]
        names = [name for name, _ in members]
        if not members or len(names) != len(set(names)):
            raise ValueError(f'{rel}: no members or clashing names {names}')
        lines += ['', f'class {cls}(StrEnum):', f'    """{doc} QLib `{cls}`, id key `{id_key[1]}`."""', '']
        lines += [f'    {name} = {value!r}' for name, value in members]
        lines.append('')
    lines += ['', '# QLib id key per enum: the `key` in `key:value` qualifiers.']
    lines.append('ID_KEYS: dict[type[StrEnum], str] = {')
    lines += [f'    {cls}: {key!r},' for cls, key in id_keys]
    lines.append('}')
    for const, rel, cls in CODE_SETS:
        values = sorted(value for _, value in _parse((source / rel).read_text(encoding='utf-8-sig'), cls))
        lines += ['', f'# QLib `{cls}` hard-coded values; QLib accepts others at runtime.']
        lines.append(f'{const}: frozenset[str] = frozenset({{')
        lines += [f'    {value!r},' for value in values]
        lines.append('})')
    return '\n'.join(lines) + '\n'


def main() -> int:
    """Write the module, or with --check report whether it is stale."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE, help='QLib Market source folder')
    parser.add_argument('--check', action='store_true', help='fail if the generated module is stale')
    args = parser.parse_args()
    if not args.source.is_dir():
        print(f'QLib source not found: {args.source}', file=sys.stderr)
        return 2
    output = render(args.source)
    if args.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        if current != output:
            print(f'{TARGET} is stale; run scripts/sync_qlib_enums.py', file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(output, encoding='utf-8', newline='\n')
    print(f'wrote {TARGET}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
